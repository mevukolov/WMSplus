-- Bug found via user report: "Аннулирование после списания" вычисляет
-- reopen_after от due_date (маркетплейсовый прогноз списания), но к моменту,
-- когда оператор реально ставит этот вердикт, due_date чаще всего уже
-- наступил или прошёл -- это и есть типичный повод его поставить. Тогда
-- reopen_after оказывается уже в прошлом, и auto_reopen_wms_tasks() (крутится
-- каждые 5 мин) тут же откатывает задачу обратно в "Не начато": задача
-- бесконечно скачет между "Отложено" и "Не начато" и никогда не закрывается.
-- Проверено по истории за 30 дней: 5 из 14 простановок этого вердикта попали
-- в петлю (переоткрытие через 0-10 часов после простановки).
--
-- Клиентский фикс (tasks.js, reopenAfterForVerdict) теперь падает на обычный
-- минимальный буфер вместо уже прошедшей даты, если due_date-кандидат уже не
-- в будущем -- но это не трогает уже сохранённые в БД испорченные значения.
-- Эта миграция один раз поднимает их до того же буфера.
update public.wms_tasks
set reopen_after = now() + interval '2 days',
    updated_at = now()
where task_status = 'Отложено'
  and opp_verdict = 'Аннулирование после списания'
  and reopen_after <= now();
