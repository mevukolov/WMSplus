-- Привязка типов нарушений к участкам редактируется в Маршрутизаторе.
-- Пустой массив означает «не предлагать тип сотрудникам ни на одном
-- участке», поэтому новые типы сначала настраиваются явно.
alter table public.wms_violation_types
    add column if not exists zones text[] not null default '{}'::text[];

-- Начальная матрица повторяет действующую логику формы. Обновляем только
-- ещё не настроенные строки: последующие изменения из Маршрутизатора эта
-- миграция не перезапишет при повторном запуске.
update public.wms_violation_types
set zones = case label
    when 'Не отнёс задвойку/Пустую упаковку' then array['Упаковка', 'ПЦ', 'Без заказа']
    when 'Бессистемно вложен на КС' then array['ПМ', 'Почта', 'Предсортировка', 'Маркетплейс', 'ПЦ', 'WMI (МП + ПЦ)', 'Упаковка', 'Без заказа', 'Движение после продажи']
    when 'Кинул мимо сетки' then array['ПМ', 'Почта', 'Предсортировка', 'Маркетплейс', 'ПЦ', 'WMI (МП + ПЦ)']
    when 'Неверное вложение в сетку МП' then array['ПМ', 'Маркетплейс', 'WMI (МП + ПЦ)']
    when 'Пикнули вещи из транзитной сетки' then array['ПМ', 'Маркетплейс', 'WMI (МП + ПЦ)', 'Предсортировка']
    when 'Отгружена под пустой передачей после КГТ' then array['Упаковка', 'ПЦ', 'Движение после продажи']
    when 'Пик в гофре/Вне зоны видимости камер' then array['Упаковка', 'ПЦ', 'Предсортировка']
    when 'Проблемы с ротацией на КГТ' then array['Упаковка', 'ПЦ', 'Движение после продажи']
    when 'Не отнес левак' then array['ПМ', 'Почта', 'Предсортировка', 'Маркетплейс', 'ПЦ', 'WMI (МП + ПЦ)', 'Без заказа']
    when 'Ошибка отдела Брак' then array['Упаковка', 'ПЦ', 'Другие задачи']
    when 'Ошибка администрации' then array['Упаковка', 'RWP', 'ПМ', 'Почта', 'Предсортировка', 'Маркетплейс', 'ПЦ', 'WMI (МП + ПЦ)', 'Без заказа', 'Движение после продажи', 'Другие задачи', 'Чистые списания']
    when 'Бессистемное вложение в сетку упака после МП' then array['ПМ', 'Маркетплейс', 'WMI (МП + ПЦ)', 'Упаковка']
    when 'Обработка на МП товара, непредназначеного для МП' then array['ПМ', 'Маркетплейс', 'WMI (МП + ПЦ)']
    when 'Неверное вложение в сетку' then array['ПМ', 'Почта', 'Предсортировка', 'Маркетплейс', 'ПЦ', 'WMI (МП + ПЦ)']
    when 'Отправлен под пустым стикером' then array['Упаковка', 'ПЦ', 'Движение после продажи', 'Без заказа']
    when 'Присвоен стикер от другого товара' then array['ПМ', 'Почта', 'Предсортировка', 'Маркетплейс', 'ПЦ', 'WMI (МП + ПЦ)', 'Упаковка', 'Без заказа']
    when 'Отложил в слепую зону' then array['Упаковка', 'ПМ', 'Почта', 'Предсортировка', 'Маркетплейс', 'ПЦ', 'WMI (МП + ПЦ)', 'Без заказа', 'Движение после продажи']
    when 'Другое' then array['Упаковка', 'RWP', 'ПМ', 'Почта', 'Предсортировка', 'Маркетплейс', 'ПЦ', 'WMI (МП + ПЦ)', 'Без заказа', 'Движение после продажи', 'Другие задачи', 'Чистые списания']
    else zones
end
where cardinality(zones) = 0;
